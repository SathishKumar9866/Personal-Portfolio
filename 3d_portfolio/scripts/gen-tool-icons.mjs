/**
 * Generates `src/components/toolIcons.js` from the `simple-icons` package.
 *
 * WHY A GENERATOR AND NOT A DEPENDENCY. `simple-icons` is 3,460 marks and the
 * site needs about twenty-five. Importing it at runtime — even by subpath —
 * puts a package this size in the dependency graph for a handful of glyphs.
 * Here it is a devDependency: this script reads the paths once, writes the ones
 * the site actually renders into a plain module, and that module is what ships.
 *
 * WHY NOT HAND-WRITTEN PATHS. The repo already hand-writes four brand glyphs in
 * `icons.js`, so the precedent exists — but those four were checked by eye
 * against the real marks. Twenty-five recalled from memory would be twenty-five
 * chances to ship a logo that is subtly wrong, which is worse than no logo.
 *
 * The map below is explicit on purpose. An automatic slug guess
 * ("PySpark" -> "pyspark") silently matches the wrong project as often as the
 * right one, and a portfolio that labels PySpark with someone else's mark is a
 * worse error than a missing icon.
 *
 * Run: npm run icons
 */
import { writeFileSync } from "node:fs";
import * as si from "simple-icons";

/**
 * name as it appears in `constants` -> simple-icons slug.
 * `null` means "this is a concept, not a product": RAG, MLOps and Evaluation
 * have no mark, and inventing one would be a claim about a thing that does not
 * exist. Those terms render with no icon, deliberately.
 */
const MAP = {
  // data
  PySpark: "apachespark",
  PostgreSQL: "postgresql",
  // No Amazon or Microsoft marks in simple-icons any more: the project removed
  // several large corporate logos over trademark policy. Absent upstream is a
  // better reason to show nothing than any substitute would be.
  DynamoDB: null,
  S3: null,
  SQL: null,
  "ETL pipelines": null,
  // science
  pandas: "pandas",
  NumPy: "numpy",
  "scikit-learn": "scikitlearn",
  Evaluation: null,
  "Exploratory analysis": null,
  // llm
  LangChain: "langchain",
  LangGraph: "langgraph",
  Ollama: "ollama",
  Claude: "claude",
  Pinecone: null, // not in simple-icons
  Embeddings: null,
  RAG: null,
  LLM: null,
  // vision
  YOLOv8: "ultralytics",
  OpenCV: "opencv",
  PyTorch: "pytorch",
  "Detection & tracking": null,
  "Federated learning": null,
  Federated: null,
  Vision: null,
  // mlops
  MLflow: "mlflow",
  Docker: "docker",
  "GitHub Actions": "githubactions",
  Kubernetes: "kubernetes",
  Helm: "helm",
  MLOps: null,
  // backend and apps
  Python: "python",
  FastAPI: "fastapi",
  "Next.js": "nextdotjs",
  React: "react",
  TypeScript: "typescript",
  Tauri: "tauri",
  // named in roles and projects
  Neo4j: "neo4j",
  Azure: null, // see the Amazon/Microsoft note above
  Databricks: "databricks",
  "Applied ML": null,
  Multimodal: null,
  Product: null,
  Live: null,
};

const camel = (slug) =>
  "si" + slug.charAt(0).toUpperCase() + slug.slice(1);

/**
 * NO ROUNDING. An earlier version shortened coordinates to two decimals with
 * `d.replace(/\d*\.\d+/g, ...)`, which cut 44kB of path data to 31.6kB and
 * quietly corrupted every mark that uses compact arc syntax: in `a5.5 5.5 0
 * 01.5.5` the two arc FLAGS and the next coordinate are written `01.5`, and a
 * regex that sees a number there turns three tokens into one. Docker, MLflow
 * and Kubernetes rendered blank or as a dot; the file still parsed, the build
 * still passed, and only looking at the page showed it.
 *
 * The saving was not worth a parser. These paths ship in a lazy chunk that
 * nothing waits on, so their size costs first paint nothing at all.
 */

const out = {};
const missing = [];
const concepts = [];

for (const [name, slug] of Object.entries(MAP)) {
  if (slug === null) {
    concepts.push(name);
    continue;
  }
  const icon = si[camel(slug)];
  if (!icon) {
    missing.push(`${name} (${slug})`);
    continue;
  }
  out[name] = { p: icon.path };
}

const body = `/**
 * GENERATED by scripts/gen-tool-icons.mjs from the simple-icons package.
 * Do not edit by hand: run \`npm run icons\` instead, and change the name-to-slug
 * map in that script.
 *
 * ${Object.keys(out).length} marks, for the tools this site names. A term with no entry
 * renders with no icon, which is the correct answer for a concept: ${concepts.length} of
 * the names here — RAG, MLOps, Evaluation and the rest — are ideas, not products,
 * and have no mark to show.
 *
 * \`p\` is the 24x24 path exactly as simple-icons ships it. No title field: the glyph is
 * always \`aria-hidden\` beside its own name in text, so it never needs one.
 * Every path is drawn in currentColor, never the brand hex: thirty coloured
 * logos in one section is the badge wall this page's own copy argues against.
 */
export const TOOL_ICONS = ${JSON.stringify(out, null, 2)};

/** Marks available, for a quick check in the console. */
export const ICON_COUNT = ${Object.keys(out).length};
`;

writeFileSync(new URL("../src/components/toolIcons.js", import.meta.url), body);

console.log(`wrote ${Object.keys(out).length} marks`);
if (missing.length) console.log(`NO SUCH SLUG (${missing.length}): ${missing.join(", ")}`);
console.log(`no mark by design (${concepts.length}): ${concepts.join(", ")}`);
